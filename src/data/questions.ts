// Kimlik metinden türetilir: soru eklense/sırası değişse de geçmiş cevaplar doğru soruya bağlı kalır
function hid(s: string) {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0;
  return (h >>> 0).toString(36);
}

const base: Question[] = rows.map(([topic, text, options, answer]) => ({
  id: `b-${topic}-${hid(text + options.join('|'))}`,
  topic,
  text,
  options,
  answer,
  source: 'ozgun',
}));

const known = new Set(topics.map((t) => t.id));
// Hatalı kayıtlar (5 şık değil, cevap aralık dışı, bilinmeyen konu) sessizce elenir
const extra: Question[] = genQuestions
  .filter((q) => known.has(q.topic) && q.options?.length === 5 && q.answer >= 0 && q.answer < 5 && q.text)
  .map((q) => ({ ...q, id: `g-${q.topic}-${hid((q.passage ?? '') + q.text + q.options.join('|'))}`, source: 'ozgun' as const }));

const osym: Question[] = osymQuestions
  .filter((q) => known.has(q.topic) && q.options?.length === 5 && q.answer >= 0 && q.answer < 5)
  .map((q) => ({ ...q, id: `o-${q.exam}-${q.no}`, source: 'osym' as const }));

export const questions: Question[] = [...base, ...extra, ...osym];

// Paragraf içindeki soruların asıl sırası: ÖSYM'de kitapçık numarası, özgünde veri dosyasındaki sıra
const pos = new Map(questions.map((q, i) => [q.id, i]));
export const bySource = (a: Question, b: Question) => (a.no ?? 0) - (b.no ?? 0) || (pos.get(a.id) ?? 0) - (pos.get(b.id) ?? 0);

export const topicName = (id: string) => topics.find((t) => t.id === id)?.name ?? id;
